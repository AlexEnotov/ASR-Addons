// Usage: node tools/import-legend-catalog.cjs <directory with index.json and legends.json>
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const directory = process.argv[2];
assert(directory, 'Pass the directory containing the official v1 JSON files');
const read = name => JSON.parse(fs.readFileSync(path.join(directory, name), 'utf8'));
const index = read('index.json');
const legends = read('legends.json');
assert.equal(index.schema, 1);
assert.match(index.content, /^[a-f0-9]+$/);
assert.equal(legends.length, index.files['legends.json'].count);

function toLua(value) {
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) return '{ ' + value.map(toLua).join(', ') + ' }';
  const fields = Object.entries(value).filter(([, entry]) => entry !== null);
  return '{ ' + fields.map(([key, entry]) => '[' + toLua(key) + '] = ' + toLua(entry)).join(', ') + ' }';
}

const seen = new Set();
const lines = [
  '-- Generated by tools/import-legend-catalog.cjs from https://azreborn.com/data/v1/legends.json.',
  '-- Content: ' + index.content,
  'ASAdvisorResolvedLegends = {',
];
for (const {key, spell, head, icon, template, form, effects, growth, fixed} of legends) {
  assert.equal(key, 'legendary:' + spell);
  assert(!seen.has(spell) && Array.isArray(effects) && effects.length > 0, key);
  seen.add(spell);
  lines.push('  ' + toLua({ key, spell, name: head, icon, template, form, effects, growth, fixed }) + ',');
}
lines.push('};', '');
fs.writeFileSync(path.join(__dirname, '..', 'CatalogExtras.lua'), lines.join('\n'));
