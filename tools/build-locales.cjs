const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'localization');
const catalog=require('../localization/catalog.json'),native=require('../localization/native.json'),names=require('../localization/name-keys.json');
const rows=fs.readFileSync(path.join(dir,'ui.tsv'),'utf8').trimEnd().split(/\r?\n/).filter(s=>s&&!s.startsWith('#'));
const codes=rows.shift().split('|').slice(1),manual={};
const format=s=>(s.match(/%(?:\d+\$)?[-+#0]*\d*(?:\.\d+)?[cdeEfgGiouqsxX%]/g)||[]).join('|');
for(const row of rows){const [key,...values]=row.split('|').map(s=>s.replace(/\\n/g,'\n').replace(/\\x20/g,' '));if(values.length!==codes.length)throw Error('Wrong language count: '+key);if(manual[key])throw Error('Duplicate key: '+key);manual[key]={};values.forEach((v,i)=>{if(format(v)!==format(key))throw Error('Format mismatch: '+key+' '+codes[i]);manual[key][codes[i]]=v;});}
const modules={ASRAdvisor:'builder',ASRStats:'stats',ASRCombatText:'combat',ASRSuite:'suite',ASREndless:'endless',ASRLoot:'loot',ASRParty:'party',ASRChat:'chat'};
const norm=s=>s.toLowerCase().replace(/[^a-z0-9%]+/g,'');
const nativeIndex=Object.fromEntries(codes.map(c=>[c,new Map(Object.entries(native[c]).map(([k,v])=>[norm(k),v]))]));
const aliases={'Crit':'Critical strike','Crit dmg':'Critical damage','Cooldown':'Cooldown reduction','Dmg reduction':'Damage reduction','Pickup':'Pickup range','Max health':'Health','Resurrections':'Lives','Additional targets':'Extra targets','Auto':'Auto','Trait':'Trait'};
function translated(english,code){
 const own=manual[english]?.[code];if(own)return own;
 const value=native[code][english]||nativeIndex[code].get(norm(aliases[english]||english));
 if(value&&format(value)===format(english))return value;
 const suffix=/^Bonus ([1-6]) ≥$/.exec(english);if(suffix&&manual.Bonus)return manual.Bonus[code]+' '+suffix[1]+' ≥';
 const heading={'ASR / SETTINGS':'Settings','ASR / STATS':'Stats','STATS · DRAG':'Stats','ASR / COMBAT TEXT':'Combat text'}[english];
 if(heading){const word=translated(heading,code);if(!word)throw Error('Missing heading component: '+heading+' '+code);return 'ASR / '+word;}
 if(english==='View: compact'||english==='View: detailed')return manual[english]?.[code];
 return undefined;
}
const luaString=s=>JSON.stringify(s);
function register(module,code,dict){for(const [key,value]of Object.entries(dict))if(/\b(?:undefined|null|NaN)\b/.test(value))throw Error('Invalid translation: '+module+' '+code+' '+key);return 'ASRLocale.RegisterTranslations('+luaString(module)+','+luaString(code)+',{\n'+Object.entries(dict).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>' ['+luaString(k)+']='+luaString(v)+',').join('\n')+'\n});\n';}
const report={};
const check=process.argv.includes('--check');
function output(file,content){if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content)throw Error('Stale localization: '+file);}else fs.writeFileSync(file,content);}
for(const [folder,module]of Object.entries(modules)){
 let out='-- Generated by tools/build-locales.cjs. Built-in translations; missing entries use English.\n';
 out+=register(module,'en',catalog[module]);report[module]={};
 for(const code of codes){const dict={};let count=0;for(const [key,en]of Object.entries(catalog[module])){const value=translated(en,code);if(value){dict[key]=value;dict[en]=value;count++;}}out+=register(module,code,dict);report[module][code]=count;}
 if(['builder','endless','party'].includes(module)){
  const keys=module==='builder'?names.builder:module==='endless'?names.world:names.classes;
  for(const code of [...codes,'ruRU']){
   const dict={};for(const key of keys){const value=native[code]?.[key];if(value)dict[key]=value;}
   out+=register(module==='endless'?'world':'names',code==='ruRU'?'ru':code,dict);
  }
 }
 output(path.join(root,folder,'Translations.lua'),out);
 output(path.join(root,folder,'Language.lua'),fs.readFileSync(path.join(dir,'Language.lua'),'utf8'));
}
console.log(JSON.stringify({manualPhrases:Object.keys(manual).length,translated:report},null,2));
